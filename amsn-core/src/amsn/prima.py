"""Structure-preserving PRIMA reduction for passive cable trees.

The full passive network is C dv/dt + G v = B i, with symmetric positive
definite diagonal C and graph-Laplacian-plus-leak G. A block Krylov basis for
G^-1 C and G^-1 B is used with congruence projection. Therefore the reduced
matrices C_r = V.T C V and G_r = V.T G V remain symmetric positive definite:
the reduced RC model is stable and passive, apart from floating-point error.
"""
from __future__ import annotations

from dataclasses import dataclass
from math import pi
from collections.abc import Sequence

import numpy as np

from .cable import CableTree


@dataclass(frozen=True, slots=True)
class PassiveReducedModel:
    """A passive port model in reduced coordinates.

    State x represents the full compartment perturbation V @ x relative to
    the uniform leak reversal potential. Port currents enter through
    input_matrix, and port voltages are input_matrix.T @ x.
    """

    port_indices: tuple[int, ...]
    basis: np.ndarray
    conductance_matrix_s: np.ndarray
    capacitance_matrix_f: np.ndarray
    input_matrix: np.ndarray

    @property
    def order(self) -> int:
        return int(self.basis.shape[1])

    @property
    def port_count(self) -> int:
        return len(self.port_indices)

    def _validated_state(self, state: np.ndarray) -> np.ndarray:
        value = np.asarray(state, dtype=float)
        if value.shape != (self.order,) or not np.all(np.isfinite(value)):
            raise ValueError("state must be a finite vector with shape (reduced_order,)")
        return value

    def port_voltages(self, state: np.ndarray) -> np.ndarray:
        """Return retained-port voltage perturbations in volts."""
        return self.input_matrix.T @ self._validated_state(state)

    def impedance_matrix(self, frequency_hz: float) -> np.ndarray:
        """Return the reduced port transfer-impedance matrix in ohms."""
        frequency = float(frequency_hz)
        if not np.isfinite(frequency) or frequency < 0.0:
            raise ValueError("frequency_hz must be finite and non-negative")
        operator = (
            self.conductance_matrix_s.astype(np.complex128)
            + 1j * (2.0 * pi * frequency) * self.capacitance_matrix_f
        )
        response = np.linalg.solve(operator, self.input_matrix)
        impedance = self.input_matrix.T @ response
        if not (
            np.all(np.isfinite(impedance.real))
            and np.all(np.isfinite(impedance.imag))
        ):
            raise FloatingPointError("non-finite reduced port impedance")
        return impedance

    def admittance_matrix(self, frequency_hz: float) -> np.ndarray:
        """Return the inverse reduced port impedance in siemens."""
        impedance = self.impedance_matrix(frequency_hz)
        return np.linalg.solve(impedance, np.eye(self.port_count))

    def step_backward_euler(
        self,
        state: np.ndarray,
        dt_s: float,
        port_current_a: np.ndarray,
    ) -> np.ndarray:
        """Advance the reduced passive state by one backward-Euler step.

        Inputs are port currents in amperes. The state is a voltage-like
        reduced coordinate and the returned state uses the same coordinates.
        """
        previous = self._validated_state(state)
        dt = float(dt_s)
        if not np.isfinite(dt) or dt <= 0.0:
            raise ValueError("dt_s must be finite and positive")
        current = np.asarray(port_current_a, dtype=float)
        if current.shape != (self.port_count,) or not np.all(np.isfinite(current)):
            raise ValueError("port_current_a must be finite with shape (port_count,)")
        lhs = self.conductance_matrix_s + self.capacitance_matrix_f / dt
        rhs = (
            (self.capacitance_matrix_f @ previous) / dt
            + self.input_matrix @ current
        )
        following = np.linalg.solve(lhs, rhs)
        if not np.all(np.isfinite(following)):
            raise FloatingPointError("non-finite state generated by reduced step")
        return following


def _apply_passive_conductance(tree: CableTree, values: np.ndarray) -> np.ndarray:
    """Apply G = diag(g_leak) + graph Laplacian without materializing G."""
    result = tree.membrane_leak_s[:, None] * values
    for child in range(1, tree.n_compartments):
        parent = int(tree.parent_index[child])
        current = tree.axial_g_s[child] * (values[child, :] - values[parent, :])
        result[child, :] += current
        result[parent, :] -= current
    return result


def _orthogonalize_block(
    candidates: np.ndarray,
    basis_columns: list[np.ndarray],
    relative_tolerance: float,
    max_order: int,
) -> np.ndarray:
    """Twice-reorthogonalized modified Gram-Schmidt for a small block."""
    accepted: list[np.ndarray] = []
    for column in range(candidates.shape[1]):
        if len(basis_columns) >= max_order:
            break
        vector = np.array(candidates[:, column], dtype=float, copy=True)
        original_norm = float(np.linalg.norm(vector))
        if not np.isfinite(original_norm):
            raise FloatingPointError("non-finite Krylov vector")
        if original_norm == 0.0:
            continue

        # A second pass controls loss of orthogonality for clustered RC modes.
        for _ in range(2):
            for existing in basis_columns:
                vector -= existing * float(np.dot(existing, vector))
            for existing in accepted:
                vector -= existing * float(np.dot(existing, vector))
        residual_norm = float(np.linalg.norm(vector))
        if not np.isfinite(residual_norm):
            raise FloatingPointError("non-finite orthogonalized Krylov vector")
        if residual_norm <= relative_tolerance * original_norm:
            continue

        vector /= residual_norm
        accepted.append(vector)
        basis_columns.append(vector)

    if not accepted:
        return np.empty((candidates.shape[0], 0), dtype=float)
    return np.column_stack(accepted)


def prima_reduce_passive_cable(
    tree: CableTree,
    retained_indices: Sequence[int],
    max_order: int = 64,
    relative_tolerance: float = 1e-12,
) -> PassiveReducedModel:
    """Build a structure-preserving PRIMA-style reduced passive cable model.

    The full linearized passive cable is C dv/dt + G v = B i. The block
    Krylov space is generated from G^-1 B and successive applications of
    -G^-1 C. Projection is congruent (V.T @ operator @ V), preserving
    positive definiteness, stability and passivity of the RC realization.

    max_order is a state-count cap, not the number of block iterations. The
    actual order can be lower when the Krylov space becomes invariant or
    reaches the number of full compartments. This is a local passive-network
    reduction; active channels and nonlinear synapses are not included.
    """
    if not isinstance(tree, CableTree):
        raise TypeError("tree must be a CableTree")
    try:
        raw_ports = tuple(retained_indices)
    except TypeError as exc:
        raise TypeError("retained_indices must be a sequence of integer indices") from exc
    if not raw_ports:
        raise ValueError("at least one retained compartment is required")

    ports: list[int] = []
    for value in raw_ports:
        if isinstance(value, (bool, np.bool_)) or not isinstance(value, (int, np.integer)):
            raise TypeError("retained compartment indices must be integers")
        index = int(value)
        if index < 0 or index >= tree.n_compartments:
            raise IndexError(
                f"retained compartment index {index} is outside "
                f"[0, {tree.n_compartments})"
            )
        ports.append(index)
    if len(ports) != len(set(ports)):
        raise ValueError("retained compartment indices must be unique")

    if isinstance(max_order, (bool, np.bool_)) or not isinstance(
        max_order, (int, np.integer)
    ):
        raise TypeError("max_order must be an integer")
    if int(max_order) <= 0:
        raise ValueError("max_order must be positive")
    tolerance = float(relative_tolerance)
    if not np.isfinite(tolerance) or not (0.0 < tolerance < 1.0):
        raise ValueError("relative_tolerance must be finite and between 0 and 1")

    n = tree.n_compartments
    order_cap = min(int(max_order), n)
    basis_columns: list[np.ndarray] = []

    # The starting block is G^-1 B, where B selects the retained current ports.
    starting_block = np.zeros((n, len(ports)), dtype=float)
    for column, port in enumerate(ports):
        unit_current = np.zeros(n, dtype=float)
        unit_current[port] = 1.0
        starting_block[:, column] = tree.solve_passive_frequency_response(
            0.0, unit_current
        )

    block = _orthogonalize_block(
        starting_block, basis_columns, tolerance, order_cap
    )
    if block.shape[1] == 0:
        raise FloatingPointError("failed to construct the initial port Krylov block")

    # Block Arnoldi on A = -G^-1 C. Tree Hines solves avoid a dense N x N G.
    while len(basis_columns) < order_cap and block.shape[1] > 0:
        candidates = np.empty_like(block)
        for column in range(block.shape[1]):
            rhs = -tree.capacitance_f * block[:, column]
            candidates[:, column] = tree.solve_passive_frequency_response(0.0, rhs)
        following = _orthogonalize_block(
            candidates, basis_columns, tolerance, order_cap
        )
        if following.shape[1] == 0:
            break
        block = following

    basis = np.column_stack(basis_columns)
    if basis.shape != (n, len(basis_columns)):
        raise RuntimeError("invalid PRIMA basis shape")

    # Congruence projection of the positive full-order C and G operators.
    capacitance_action = tree.capacitance_f[:, None] * basis
    conductance_action = _apply_passive_conductance(tree, basis)
    capacitance_reduced = basis.T @ capacitance_action
    conductance_reduced = basis.T @ conductance_action
    capacitance_reduced = 0.5 * (capacitance_reduced + capacitance_reduced.T)
    conductance_reduced = 0.5 * (conductance_reduced + conductance_reduced.T)
    input_reduced = basis[ports, :].T.copy()

    # Fail closed if numerical rank loss or implementation errors destroy
    # the positive-definite RC energy/dissipation matrices.
    try:
        np.linalg.cholesky(capacitance_reduced)
        np.linalg.cholesky(conductance_reduced)
    except np.linalg.LinAlgError as exc:
        raise FloatingPointError(
            "PRIMA projection did not preserve positive-definite C and G"
        ) from exc

    return PassiveReducedModel(
        port_indices=tuple(ports),
        basis=basis,
        conductance_matrix_s=conductance_reduced,
        capacitance_matrix_f=capacitance_reduced,
        input_matrix=input_reduced,
    )
